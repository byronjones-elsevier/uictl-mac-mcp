#!/usr/bin/env bash
# Regenerate Sources/uictl/Core/BuildInfo.swift, which embeds the output of
# libs-version.sh and sbom.sh so the binary can report them via --libs-version
# and --sbom. If Syft is missing, warn and leave the committed file untouched.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/Sources/uictl/Core/BuildInfo.swift"
work="$(mktemp -d "${TMPDIR:-/tmp}/uictl.XXXXXX")"
trap 'rm -rf "$work"' EXIT

"$root/scripts/sbom.sh" "$work" --skip-if-missing
if [ ! -f "$work/bom.json" ]; then
	echo "gen-buildinfo: no SBOM generated; leaving $out unchanged" >&2
	exit 0
fi
"$root/scripts/libs-version.sh" >"$work/libs.txt"

{
	echo "// Generated by scripts/gen-buildinfo.sh from Package.resolved. Do not edit."
	echo
	echo "enum BuildInfo {"
	echo '    static let libsVersion: String? = ##"""'
	cat "$work/libs.txt"
	echo '"""##'
	echo
	echo '    static let sbom: String? = ##"""'
	cat "$work/bom.json"
	echo '"""##'
	echo "}"
} >"$out"
echo "gen-buildinfo: wrote $out" >&2
